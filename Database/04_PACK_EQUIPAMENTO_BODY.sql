END;

-- ----------------------------------------------------------------------------
PROCEDURE PROC_RESUMO_WHATSAPP(P_CURSOR OUT SYS_REFCURSOR) IS
BEGIN
    OPEN P_CURSOR FOR
         SELECT MARCA, MODEL, COUNT(*) AS QTD
           FROM TBL_EQUIPAMENTO
          WHERE STATUS = 'IN_STOCK'
          GROUP BY MARCA, MODEL
          ORDER BY COUNT(*) DESC;
END;

END PACK_EQUIPAMENTO;
