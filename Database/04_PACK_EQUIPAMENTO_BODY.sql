BEGIN
    OPEN P_CURSOR FOR
         SELECT E.ID_EQUIPAMENTO, E.INTERNAL_UID, E.SERIAL_NUMBER,
                E.MARCA, E.MODEL, E.PROCESSADOR, E.RAM_GB, E.STORAGE_GB,
                E.CONDITION_STATUS, E.STATUS, E.OBSERVACAO, E.DATA_CADASTRO, E.DATA_ATUALIZACAO,
                FUNC_STATUS_DESCRICAO(E.STATUS) AS STATUS_DESCRICAO,
                (SELECT COUNT(*) FROM TBL_EQUIPAMENTO_UPGRADE U
                  WHERE U.ID_EQUIPAMENTO = E.ID_EQUIPAMENTO) AS TOTAL_UPGRADES
           FROM TBL_EQUIPAMENTO E
