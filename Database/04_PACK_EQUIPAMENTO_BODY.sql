                E.MARCA, E.MODEL, E.PROCESSADOR, E.RAM_GB, E.STORAGE_GB,
                E.CONDITION_STATUS, E.STATUS, E.OBSERVACAO, E.DATA_CADASTRO, E.DATA_ATUALIZACAO,
                FUNC_STATUS_DESCRICAO(E.STATUS) AS STATUS_DESCRICAO,
